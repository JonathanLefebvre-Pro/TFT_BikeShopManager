USE TFT_BikeShopManager_WebApi;

GO

--Delete StoShopck schema and all its tables
DROP TABLE IF EXISTS Shop.Orders;
DROP TABLE IF EXISTS Shop.OrderLines;
DROP TABLE IF EXISTS Shop.DeliveryNotes;
DROP TABLE IF EXISTS Shop.Sales;
DROP TABLE IF EXISTS Shop.SaleLines;
DROP TABLE IF EXISTS Shop.Invoices;
DROP TABLE IF EXISTS Shop.Payments;
DROP TABLE IF EXISTS Shop.AutiLogs;
DROP SCHEMA IF EXISTS Shop;

GO

CREATE SCHEMA Shop;

GO

CREATE TABLE Shop.Orders (
    Id INT PRIMARY KEY IDENTITY(1,1),
    CustomerId INT NOT NULL,
    EmployeeId INT NOT NULL,
    Status NVARCHAR(50) NOT NULL,
    QuoteNumber NVARCHAR(50) UNIQUE NOT NULL,
    CommandNumber NVARCHAR(50) NULL,
    QuoteValidUntil DATETIME2 NULL,
    ConfirmedAt DATETIME2 NULL,
    CreatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
    UpdatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME()
);

GO

CREATE TABLE Shop.OrderLines (
    Id INT PRIMARY KEY IDENTITY(1,1),
    OrderId INT NOT NULL,
    Type NVARCHAR(50) NOT NULL,
    ArticleId INT NULL,
    BikeModelId INT NULL,
    BikeUnitId INT NULL,
    Label NVARCHAR(50) NULL,
    Quantity INT NOT NULL CHECK(Quantity > 0),
    UnitPriceExclVat DECIMAl(12,2) NOT NULL,
    VatRateId INT NOT NULL,
    Status NVARCHAR(50) NOT NULL,
    CreatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
    UpdatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME()
);

GO

CREATE TABLE Shop.DeliveryNotes (
    Id INT PRIMARY KEY IDENTITY(1,1),
    OrderId INT UNIQUE NOT NULL,
    Status NVARCHAR(50) NOT NULL,
    CustomerNotifiedDate DATETIME2 NULL,
    CreatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
    UpdatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME()
);

GO

CREATE TABLE Shop.Sales (
    Id INT PRIMARY KEY IDENTITY(1,1),
    CustomerId INT NULL,
    EmployeeId INT NOT NULL,
    DeliveryNoteId INT NULL,
    Status NVARCHAR(50) NOT NULL,
    TotalExclVat DECIMAL(12,2) NOT NULL,
    TotalVat DECIMAL(12,2) NOT NULL,
    TotalInclVat DECIMAL(12,2) NOT NULL,
    SaleDate DATETIME2 NOT NULL,
    CreatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
    UpdatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME()
);

GO

CREATE TABLE Shop.SaleLines (
    Id INT PRIMARY KEY IDENTITY(1,1),
    SaleId INT NOT NULL,
    Label NVARCHAR(50) NOT NULL,
    Quantity INT NOT NULL CHECK(Quantity > 0),
    UnitPriceExclVat DECIMAL(12,2) NOT NULL,
    VatRate DECIMAL(5,2) NOT NULL,
    ArticleId INT NULL,
    BikeUnitId INT NULL,
    CreatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
    UpdatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME()
);

GO

CREATE TABLE Shop.Invoices (
    Id INT PRIMARY KEY IDENTITY(1,1),
    InvoiceNumber NVARCHAR(20) UNIQUE NOT NULL,
    Status NVARCHAR(20) NOT NULL,
    IssuedDate DATETIME2 NOT NULL,
    CreatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
    UpdatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME()
);

GO
CREATE TABLE Shop.Payments (
    Id INT PRIMARY KEY IDENTITY(1,1),
    SaleId INT NULL,
    OrderId INT NULL,
    Amount DECIMAL(12,2) NOT NULL CHECK(Amount > 0),
    PaymentMethod NVARCHAR(20) NOT NULL,
    PaymentDate DATETIME2 NOT NULL,
    CreatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
    UpdatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME()
);

GO

CREATE TABLE Shop.AuditLogs (
    Id INT PRIMARY KEY IDENTITY(1,1),
    EmployeeId INT NULL,
    Action NVARCHAR(50) NOT NULL,
    EntityName NVARCHAR(50) NOT NULL,
    EntityId INT NULL,
    Details NVARCHAR(MAX) NULL,
    IpAddress NVARCHAR(45) NULL,
    CreatedDate DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME()
);

GO