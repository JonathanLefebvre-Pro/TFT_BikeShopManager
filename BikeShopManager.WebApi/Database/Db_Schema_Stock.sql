USE TFT_BikeShopManager_WebApi;

GO

--Delete Stock schema and all its tables
DROP TABLE IF EXISTS Stock.VatRates;
DROP TABLE IF EXISTS Stock.Brands;
DROP TABLE IF EXISTS Stock.Categories;
DROP TABLE IF EXISTS Stock.Locations;
DROP TABLE IF EXISTS Stock.Images;
DROP TABLE IF EXISTS Stock.Articles;
DROP TABLE IF EXISTS Stock.BikeModels;
DROP TABLE IF EXISTS Stock.BikeUnits;
DROP SCHEMA IF EXISTS Stock;

GO

CREATE SCHEMA Stock;

GO

CREATE TABLE Stock.VatRates (
    Id INT PRIMARY KEY IDENTITY(1,1),
    Label NVARCHAR(50) NOT NULL,
    Rate DECIMAL(5, 2) NOT NULL,
    CreatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
    UpdatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME()
);

GO

CREATE TABLE Stock.Brands (
    Id INT PRIMARY KEY IDENTITY(1,1),
    Name NVARCHAR(50) NOT NULL UNIQUE,
    CreatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
    UpdatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME()
);

GO

CREATE TABLE Stock.Categories (
    Id INT PRIMARY KEY IDENTITY(1,1),
    Name NVARCHAR(50) NOT NULL UNIQUE,
    Description NVARCHAR(255) NULL,
    ParentCategoryId INT NULL,
    Domain NVARCHAR(50) NOT NULL,
    CreatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
    UpdatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME()
);

GO

CREATE TABLE Stock.Locations (
    Id INT PRIMARY KEY IDENTITY(1,1),
    Name NVARCHAR(50) NOT NULL UNIQUE,
    CreatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
    UpdatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME()
);

GO

CREATE TABLE Stock.Images (
    Id INT PRIMARY KEY IDENTITY(1,1),
    ArticleId INT NULL,
    BikeId INT NULL,
    Url NVARCHAR(255) NOT NULL,
    ImageName NVARCHAR(100) NOT NULL,
    CreatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
    UpdatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME()
);

GO

CREATE TABLE Stock.Articles (
    Id INT PRIMARY KEY IDENTITY(1,1),
    Name NVARCHAR(100) NOT NULL,
    BrandId INT NOT NULL,
    Description NVARCHAR(255) NULL,
    CategoryId INT NOT NULL,
    PurchasePrice DECIMAL(10, 2) NOT NULL,
    SalePrice DECIMAL(10, 2) NOT NULL,
    VatRateId INT NOT NULL,
    AvailableQuantity INT NOT NULL DEFAULT 0,
    MinQuantity INT NOT NULL DEFAULT 0,
    MaxQuantity INT NULL,
    EAN NVARCHAR(13) NULL,
    CreatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
    UpdatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME()
);

GO

CREATE TABLE Stock.BikeModels (
    Id INT PRIMARY KEY IDENTITY(1,1),
    Name NVARCHAR(100) NOT NULL,
    BrandId INT NOT NULL,
    Model NVARCHAR(100) NOT NULL,
    Description NVARCHAR(255) NULL,
    CategoryId INT NOT NULL,
    PurchasePrice DECIMAL(10, 2) NOT NULL,
    SalePrice DECIMAL(10, 2) NOT NULL,
    VatRateId INT NOT NULL,
    EAN NVARCHAR(13) NULL,
    IsActive BIT NOT NULL DEFAULT 1,
    CreatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
    UpdatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME()
);

GO

CREATE TABLE Stock.BikeUnits (
    Id INT PRIMARY KEY IDENTITY(1,1),
    BikeModelId INT NOT NULL,
    SerialNumber NVARCHAR(100) NOT NULL UNIQUE,
    LocationId INT NOT NULL,
    Status NVARCHAR(50) NOT NULL DEFAULT 'Available',
    CreatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
    UpdatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME()
);

GO